/* In-guest ECC self-test (compile-gated by Z6M_ECC_SELFTEST).
 *
 * Exercises the bn254 precompile engines through the zkvm-standards
 * accelerator ABI against known-good constants, so a zkVM port's
 * field/curve acceleration hooks (e.g. the OpenVM modular / Fp2 /
 * short-Weierstrass custom instructions) are validated end-to-end inside
 * the VM: G+G == 2G, [7]G == 7G, and the pairing identity
 * e(G1, G2) * e(-G1, G2) == 1 (plus a negative pairing check).
 *
 * On any mismatch the guest halts with a failure exit code before block
 * validation runs, making a broken hook unmissable.
 */

